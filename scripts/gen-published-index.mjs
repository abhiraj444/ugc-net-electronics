// Runs before `next build`: lists content/published/*.json so client code (nav, search, unit pages) knows which lessons are live.
import fs from 'node:fs';
import path from 'node:path';
const dir = path.join(process.cwd(), 'content', 'published');
const items = [];
if (fs.existsSync(dir)) {
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
    try {
      const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
      if (!d.id || !/^[a-z0-9-]+$/i.test(d.id) || !Array.isArray(d.blocks)) throw new Error('bad doc');
      items.push({ id: d.id, unit: d.unit || '', number: String(d.number || ''), title: String(d.title || d.id), minutes: Number(d.minutes) || 15, custom: !!d.meta?.custom });
    } catch (e) { console.warn(`[published] skipped ${f}: ${e.message}`); }
  }
}
const out = `// Generated by scripts/gen-published-index.mjs. Do not edit.\nexport type PublishedRef = { id: string; unit: string; number: string; title: string; minutes: number; custom: boolean };\nexport const PUBLISHED: PublishedRef[] = ${JSON.stringify(items, null, 2)};\n`;
fs.writeFileSync(path.join(process.cwd(), 'lib', 'publishedIndex.ts'), out);
console.log(`[published] ${items.length} published lesson(s) indexed`);
